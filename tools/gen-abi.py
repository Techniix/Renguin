#!/usr/bin/env python3
"""Generate Renguin's Linux ABI headers from a FreeBSD source tree.

Usage: gen-abi.py FREEBSD_SRC OUTPUT_DIR [FREEBSD_COMMIT]

Writes into OUTPUT_DIR:
  linux_errno.h          FreeBSD sys/compat/linux/linux_errno.h, unmodified
                         (BSD-2-Clause; its notice is kept).
  linux_errno_table.h    {native errno name, Linux errno} pairs, generated
                         from the left/right columns of FreeBSD's
                         linux_errtbl in sys/compat/linux/linux_errno.inc.
                         Each pair is guarded by #ifdef so names Haiku does
                         not have drop out.
  linux_syscall_names.h  Linux x86-64 syscall number -> FreeBSD handler name,
                         from sys/amd64/linux/syscalls.master. Used for
                         logging unimplemented calls.
"""
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
commit = sys.argv[3] if len(sys.argv) > 3 else "unknown"
os.makedirs(out, exist_ok=True)
note = f"Generated by tools/gen-abi.py from FreeBSD commit {commit}. Do not edit."

# 1. errno values, copied unmodified.
errno_h = open(os.path.join(src, "sys/compat/linux/linux_errno.h")).read()
with open(os.path.join(out, "linux_errno.h"), "w") as f:
    f.write(f"/* Copied unmodified from FreeBSD sys/compat/linux/linux_errno.h,\n"
            f" * commit {commit}. */\n")
    f.write(errno_h)

# 2. native -> Linux errno pairs.
inc = open(os.path.join(src, "sys/compat/linux/linux_errno.inc")).read()
table = inc[inc.index("linux_errtbl[ELAST + 1]"):]
table = table[:table.index("};")]
pairs = re.findall(r"\[(E[A-Z0-9]+)\]\s*=\s*-(LINUX_E[A-Z0-9]+)", table)
if len(pairs) < 90:
    sys.exit(f"only {len(pairs)} errno pairs found; FreeBSD format changed?")
with open(os.path.join(out, "linux_errno_table.h"), "w") as f:
    f.write(f"/* {note}\n * Derived from FreeBSD linux_errno.inc (BSD-2-Clause). */\n")
    f.write("/* Each line: RENGUIN_ERRNO(native name, Linux value) */\n")
    for native, linux in pairs:
        f.write(f"#ifdef {native}\nRENGUIN_ERRNO({native}, {linux})\n#endif\n")

# 3. syscall names.
master = open(os.path.join(src, "sys/amd64/linux/syscalls.master")).read()
entries = re.findall(
    r"^(\d+)\s+AUE_\w+\s+(?:STD|NOPROTO)\s*\{\s*\n?\s*[\w ]*?\b(\w+)\s*\(",
    master, re.M)
names = {}
for number, name in entries:
    for prefix in ("linux_sys_", "linux_"):
        if name.startswith(prefix):
            name = name[len(prefix):]
            break
    names[int(number)] = name
count = max(names) + 1
with open(os.path.join(out, "linux_syscall_names.h"), "w") as f:
    f.write(f"/* {note}\n * Derived from FreeBSD sys/amd64/linux/syscalls.master (BSD-2-Clause). */\n")
    f.write(f"#define LINUX_SYSCALL_COUNT {count}\n\n")
    f.write("static const char* const kLinuxSyscallNames[LINUX_SYSCALL_COUNT] = {\n")
    for n in range(count):
        if n in names:
            f.write(f'\t/* {n} */ "{names[n]}",\n')
        else:
            f.write(f"\t/* {n} */ NULL,\n")
    f.write("};\n")

print(f"{len(pairs)} errno pairs, {len(names)} syscall names, count {count}")
